-- ============================================================
-- FARE KERALAM V1
-- SOURCE-INTEGRATED DATABASE
-- PostgreSQL / Supabase
-- NO GPT
-- ============================================================

CREATE TABLE IF NOT EXISTS vehicle_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    requires_model BOOLEAN NOT NULL DEFAULT FALSE,
    requires_seating_capacity BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS energy_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    unit TEXT NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL
        REFERENCES vehicle_categories(id)
        ON DELETE RESTRICT,
    energy_source_id BIGINT
        REFERENCES energy_sources(id)
        ON DELETE RESTRICT,
    name TEXT,
    seating_capacity INTEGER,
    efficiency NUMERIC(12,4),
    efficiency_unit TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (seating_capacity IS NULL OR seating_capacity > 0),
    CHECK (efficiency IS NULL OR efficiency > 0)
);

CREATE TABLE IF NOT EXISTS data_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    organization TEXT NOT NULL,
    url TEXT NOT NULL,
    data_type TEXT NOT NULL,
    source_level TEXT NOT NULL DEFAULT 'official'
        CHECK (
            source_level IN (
                'official',
                'government_statistics',
                'regulated',
                'market',
                'secondary'
            )
        ),
    update_frequency TEXT,
    automatic_update_supported BOOLEAN NOT NULL DEFAULT FALSE,
    verification_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            verification_status IN (
                'pending',
                'verified',
                'expired',
                'unavailable'
            )
        ),
    last_checked_at TIMESTAMPTZ,
    last_successful_update_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS source_updates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL
        REFERENCES data_sources(id)
        ON DELETE CASCADE,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status TEXT NOT NULL
        CHECK (
            status IN (
                'success',
                'failed',
                'changed',
                'unchanged',
                'manual_review'
            )
        ),
    records_added INTEGER NOT NULL DEFAULT 0,
    records_updated INTEGER NOT NULL DEFAULT 0,
    records_rejected INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    notes TEXT
);

CREATE TABLE IF NOT EXISTS fare_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL
        REFERENCES vehicle_categories(id)
        ON DELETE RESTRICT,
    energy_source_id BIGINT
        REFERENCES energy_sources(id)
        ON DELETE RESTRICT,
    minimum_fare NUMERIC(12,2) NOT NULL,
    minimum_distance_km NUMERIC(10,2) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    source_id BIGINT
        REFERENCES data_sources(id)
        ON DELETE SET NULL,
    government_reference TEXT,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'active', 'expired')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (minimum_fare >= 0),
    CHECK (minimum_distance_km >= 0),
    CHECK (
        effective_to IS NULL
        OR effective_to >= effective_from
    )
);

CREATE TABLE IF NOT EXISTS fare_slabs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fare_rule_id BIGINT NOT NULL
        REFERENCES fare_rules(id)
        ON DELETE CASCADE,
    from_km NUMERIC(10,2) NOT NULL,
    to_km NUMERIC(10,2),
    rate_per_km NUMERIC(12,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (from_km >= 0),
    CHECK (to_km IS NULL OR to_km > from_km),
    CHECK (rate_per_km >= 0)
);

CREATE TABLE IF NOT EXISTS cost_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cost_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_category_id BIGINT NOT NULL
        REFERENCES cost_categories(id)
        ON DELETE RESTRICT,
    energy_source_id BIGINT
        REFERENCES energy_sources(id)
        ON DELETE SET NULL,
    value NUMERIC(14,4) NOT NULL,
    unit TEXT NOT NULL,
    location TEXT NOT NULL DEFAULT 'Kerala',
    district TEXT,
    effective_date DATE NOT NULL,
    source_id BIGINT
        REFERENCES data_sources(id)
        ON DELETE SET NULL,
    source_reference TEXT,
    retrieved_at TIMESTAMPTZ,
    verification_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            verification_status IN (
                'pending',
                'verified',
                'rejected'
            )
        ),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (value >= 0)
);

CREATE TABLE IF NOT EXISTS price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_category_id BIGINT NOT NULL
        REFERENCES cost_categories(id),
    energy_source_id BIGINT
        REFERENCES energy_sources(id)
        ON DELETE SET NULL,
    value NUMERIC(14,4) NOT NULL,
    unit TEXT NOT NULL,
    location TEXT NOT NULL DEFAULT 'Kerala',
    district TEXT,
    price_date DATE NOT NULL,
    source_id BIGINT
        REFERENCES data_sources(id)
        ON DELETE SET NULL,
    source_reference TEXT,
    retrieved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (value >= 0)
);

CREATE TABLE IF NOT EXISTS historical_fares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL
        REFERENCES vehicle_categories(id),
    energy_source_id BIGINT
        REFERENCES energy_sources(id),
    minimum_fare NUMERIC(12,2),
    minimum_distance_km NUMERIC(10,2),
    effective_from DATE NOT NULL,
    effective_to DATE,
    source_id BIGINT
        REFERENCES data_sources(id)
        ON DELETE SET NULL,
    government_reference TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cost_index_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_category_id BIGINT NOT NULL
        REFERENCES cost_categories(id),
    index_value NUMERIC(14,6) NOT NULL,
    reference_period DATE NOT NULL,
    location TEXT NOT NULL DEFAULT 'Kerala',
    source_id BIGINT
        REFERENCES data_sources(id)
        ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS calculation_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT
        REFERENCES vehicle_categories(id)
        ON DELETE SET NULL,
    energy_source_id BIGINT
        REFERENCES energy_sources(id)
        ON DELETE SET NULL,
    vehicle_id BIGINT
        REFERENCES vehicles(id)
        ON DELETE SET NULL,
    distance_km NUMERIC(10,2) NOT NULL,
    official_fare NUMERIC(12,2),
    operating_cost_estimate NUMERIC(12,2),
    calculation_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (distance_km >= 0)
);

