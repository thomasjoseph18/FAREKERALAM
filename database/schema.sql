CREATE INDEX IF NOT EXISTS idx_vehicles_category
    ON vehicles(category_id);

CREATE INDEX IF NOT EXISTS idx_vehicles_energy
    ON vehicles(energy_source_id);

CREATE INDEX IF NOT EXISTS idx_fare_rules_category
    ON fare_rules(category_id);

CREATE INDEX IF NOT EXISTS idx_fare_rules_dates
    ON fare_rules(effective_from, effective_to);

CREATE INDEX IF NOT EXISTS idx_fare_slabs_rule
    ON fare_slabs(fare_rule_id);

CREATE INDEX IF NOT EXISTS idx_cost_data_category
    ON cost_data(cost_category_id);

CREATE INDEX IF NOT EXISTS idx_cost_data_date
    ON cost_data(effective_date);

